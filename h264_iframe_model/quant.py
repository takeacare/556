# 量化步长基准 ROM（Qp%6 对应的基准步长），Qp//6 部分再按 2 的幂缩放。
_QSTEP_BASE = [0.625, 0.6875, 0.8125, 0.875, 1.0, 1.125]


def _clip_qp(qp: int) -> int:
    """把 Qp 限制在标准合法范围 0..51。"""
    if qp < 0:
        return 0
    if qp > 51:
        return 51
    return qp


def quant_step(qp: int) -> float:
    """返回该 Qp 的量化步长 Qstep（标准 H.264 步长，可能为小数）。

    Qstep = 基准步长[Qp%6] * 2^(Qp//6)，基准步长表固化为 ROM 单周期读出。
    """
    qp = _clip_qp(qp)
    return _QSTEP_BASE[qp % 6] * (1 << (qp // 6))


def quantize_4x4(coeffs: list, qp: int, is_ac: bool = False) -> list:
    """4x4 前向量化：level = sign · ((|W|·MF + f) >> qbits)。

    MF 查表（ROM）按 Qp%6 与系数位置索引；qbits = 15 + Qp//6；f 为帧内
    舍入偏移 (1<<qbits)//3。is_ac=True 表示 AC 块，DC 位置 (0,0) 不量化
    （留 0，DC 由独立的 DC 变换/量化通道处理）。量化保持系数符号。
    """
    qp = _clip_qp(qp)
    qpher = qp % 6
    qp_rem = qp // 6
    qbits = 15 + qp_rem
    f = (1 << qbits) // 3  # 帧内编码舍入偏移
    mf = QUANT_MF[qpher]
    out = [[0] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            if is_ac and i == 0 and j == 0:
                continue  # AC 块 DC 位置留空
            v = coeffs[i][j]
            a = v if v >= 0 else -v
            level = (a * mf[i][j] + f) >> qbits
            out[i][j] = level if v >= 0 else -level
    return out


def dequantize_4x4(levels: list, qp: int, is_ac: bool = False) -> list:
    """4x4 反量化：W = level · V << (Qp//6)。

    V 查表（ROM）按 Qp%6 与系数位置索引。is_ac 语义与 quantize_4x4 一致。
    """
    qp = _clip_qp(qp)
    qpher = qp % 6
    qp_rem = qp // 6
    v_tab = DEQUANT_V[qpher]
    out = [[0] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            if is_ac and i == 0 and j == 0:
                continue
            out[i][j] = (levels[i][j] * v_tab[i][j]) << qp_rem
    return out
