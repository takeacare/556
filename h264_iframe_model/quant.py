"""量化与反量化（技术文档 3.2.3 节第 3 点）。

使用 H.264 标准量化：前向量化因子 MF 表与反向缩放因子 V 表均按 Qp%6
索引，Qp//6 控制左移/右移位数，全程定点乘加移位、无浮点。MF/V 表按系数
位置（行列奇偶性）区分 DC 位置与 AC 位置。

量化步长表固化为 ROM，单周期查表：quant_step() 即该 ROM 的读出；量化/
反量化的 MF、V 同样为 ROM 查表（Qp%6 + 位置索引）。
"""

